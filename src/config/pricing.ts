/** Public South African starting-price ladder generated by the shared engine. */
export const BASE_ZAR_MONTHLY = (['starter', 'growth', 'pro', 'business', 'enterprise'] as FastCheckInPackage[]).map((plan) => getStartingPrice(plan, 'monthly')) as [number, number, number, number, number];
export const BASE_ZAR_YEARLY = (['starter', 'growth', 'pro', 'business', 'enterprise'] as FastCheckInPackage[]).map((plan) => getStartingPrice(plan, 'yearly')) as [number, number, number, number, number];

/** Convert the authoritative ZAR price using the current server-controlled buffered FX rate and regional adjustment. */
export function convertZarToRegionalPrice(
  zarAmount: number,
  region: MarketRegion,
  southAfrican = false,
  fxRates?: Partial<Record<'USD' | 'EUR', PricingFxRate>>,
): number {
  if (southAfrican) return Math.round(zarAmount);
  const config = MARKET_CONFIG[region];
  const rates = fxRates ?? getCachedFxRates();
  const fallback = config.currency === 'EUR' ? LAST_KNOWN_SAFE_ZAR_PER_EUR : LAST_KNOWN_SAFE_ZAR_PER_USD;
  const zarPerUnit = rates[config.currency]?.pricingRateZarPerUnit ?? fallback;
  return Math.round((zarAmount / zarPerUnit) * config.pricingMultiplier);
}

export function getRegionalPricing(
  region: MarketRegion,
  southAfrican = false,
  fxRates?: Partial<Record<'USD' | 'EUR', PricingFxRate>>,
): RegionalPlanPricing {
  if (southAfrican) {
    return {
      currency: 'ZAR',
      prices: BASE_ZAR_MONTHLY.map((monthly, index) => ({ monthly, yearly: BASE_ZAR_YEARLY[index] })),
      billingCurrency: 'ZAR',
      exchangeRateVariable: true,
    };
  }

  const config = MARKET_CONFIG[region];
  const monthlyPrices = BASE_ZAR_MONTHLY.map((monthly) => convertZarToRegionalPrice(monthly, region, false, fxRates));
  return {
    currency: config.currency,
    prices: monthlyPrices.map((monthly) => ({ monthly, yearly: monthly * 11 })),
    billingCurrency: 'ZAR',
    exchangeRateVariable: true,
  };
}
