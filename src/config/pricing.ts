import { MARKET_CONFIG, type MarketRegion } from './markets';

export interface RegionalPlanPrice {
  monthly: number;
  yearly: number;
}

export interface PricingFxRate {
  marketRateZarPerUnit: number;
  bufferPercent: number;
  pricingRateZarPerUnit: number;
  effectiveFrom?: string;
  source?: string;
}

export interface RegionalPlanPricing {
  currency: 'ZAR' | 'USD' | 'EUR';
  prices: RegionalPlanPrice[];
  billingCurrency: 'ZAR';
  exchangeRateVariable: true;
}

/**
 * Last-known safe rates are resilience fallbacks only. The authoritative
 * rates are maintained server-side in Supabase and loaded by the pricing
 * context. These values are not build-time configuration and cannot override
 * the server-controlled rates.
 */
export const LAST_KNOWN_SAFE_ZAR_PER_USD = 21.23 * 1.05;
export const LAST_KNOWN_SAFE_ZAR_PER_EUR = 18.94 * 1.05;
const FX_RATES_KEY = 'fastcheckin.pricing.fxRates';

function getCachedFxRates(): Partial<Record<'USD' | 'EUR', PricingFxRate>> {
  if (typeof window === 'undefined') return {};
  try {
    return JSON.parse(window.localStorage.getItem(FX_RATES_KEY) || '{}');
  } catch {
    return {};
  }
}

