-- Peach Orchestration webhook inbox.
-- Apply this migration to Supabase before enabling the LIVE webhook.
create table if not exists public.peach_webhook_events (
  id bigint generated by default as identity primary key,
  webhook_id text not null unique,
  profile_id text,
  event_type text,
  event_status text,
  payload jsonb,
  raw_body text not null,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  processing_status text not null default 'received',
  processing_error text
);

create index if not exists peach_webhook_events_received_at_idx
  on public.peach_webhook_events (received_at desc);

alter table public.peach_webhook_events enable row level security;

-- No client policies are intentionally created. Only trusted server-side
-- service-role access should read/write this table.
